"""Turns Aloboi_Synth.sf2 (a SoundFont with one looped sample) into a Swift source file the engine embeds.

Usage:
    python make_aloboi_sample.py <Aloboi_Synth.sf2> <output AloboiSampleData.swift>

Only the Python standard library is used. The sample is kept from its first frame up to the end of its loop
(the part after the loop is never played), as 16-bit mono PCM, base64 text in a multi-line Swift string.
Playing the sample at the pitch of the song's notes is done by AloboiSample.swift.
"""
import base64
import struct
import sys

sf2_path, out_path = sys.argv[1], sys.argv[2]
data = open(sf2_path, "rb").read()
assert data[:4] == b"RIFF" and data[8:12] == b"sfbk", "not a SoundFont (.sf2) file"


def chunks(buf, start, end):
    i = start
    while i + 8 <= end:
        cid = buf[i:i + 4]
        size = struct.unpack_from("<I", buf, i + 4)[0]
        yield cid, i + 8, size
        i += 8 + size + (size & 1)


smpl = None
shdr = None
for cid, off, size in chunks(data, 12, len(data)):
    if cid != b"LIST":
        continue
    kind = data[off:off + 4]
    for sid, soff, ssize in chunks(data, off + 4, off + size):
        if kind == b"sdta" and sid == b"smpl":
            smpl = data[soff:soff + ssize]
        elif kind == b"pdta" and sid == b"shdr":
            shdr = data[soff:soff + ssize]
assert smpl is not None and shdr is not None, "no sample found"

# First sample header (46 bytes each): name(20) start end loopStart loopEnd rate pitch correction link type
start, end, loop_start, loop_end, rate, root_key, correction, link, kind = struct.unpack_from("<IIIIIBbHH", shdr, 20)
assert start == 0 and 0 < loop_start < loop_end <= end, "unexpected sample layout"
loop_len = loop_end - loop_start
frames = loop_end  # everything before the end of the loop; the tail after it is never played

# The loop holds a whole number of cycles of the sample's pitch, so the exact frequency the sample sounds at
# is cycles * rate / loop length. Measured with an autocorrelation of the loop: the waveform repeats every
# 1/10 of the loop (correlation 0.64; at 1/20 of the loop it is -0.26), so the loop holds 10 cycles and the
# sample sounds at about 129.3 Hz, a little under C3 (the SoundFont's root key 60 is an octave too high).
CYCLES_IN_LOOP = 10
root_hz = CYCLES_IN_LOOP * rate / loop_len

pcm = smpl[start * 2:frames * 2]
text = base64.b64encode(pcm).decode("ascii")
lines = [text[i:i + 100] for i in range(0, len(text), 100)]

with open(out_path, "w", newline="\n") as f:
    f.write("// Generated by scripts/make_aloboi_sample.py from Aloboi_Synth.sf2. Do not edit by hand.\n")
    f.write("// 16-bit mono PCM, base64, from the first frame to the end of the loop.\n\n")
    f.write("enum AloboiSampleData {\n")
    f.write("    static let sampleRate: Double = %d\n" % rate)
    f.write("    /// The frequency the sample sounds at (20 cycles fit exactly into the loop).\n")
    f.write("    static let rootHz: Double = %.6f\n" % root_hz)
    f.write("    static let loopStart = %d\n" % loop_start)
    f.write("    static let loopEnd = %d\n" % loop_end)
    f.write('    static let base64 = """\n')
    for line in lines:
        f.write(line + "\n")
    f.write('"""\n')
    f.write("}\n")

print("frames kept:", frames, "| loop:", loop_start, "-", loop_end, "| rate:", rate, "| root Hz: %.4f" % root_hz)
print("wrote", out_path, "(%d characters of base64)" % len(text))
